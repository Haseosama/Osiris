    private val BY_ICAO: Map<String, FlightAirport> = ALL.mapNotNull { ap -> ap.icao?.let { it to ap } }.toMap()
    private val BY_IATA: Map<String, FlightAirport> = ALL.mapNotNull { ap -> ap.iata?.takeIf { it.isNotBlank() }?.let { it to ap } }.toMap()

    /** Look up by ICAO (4-char) or IATA (3-char) code — used to resolve the origin/destination
     * codes returned by route-lookup sources (see [com.osiris.app.data.source.FlightRouteSource])
     * into real coordinates. No dynamic ADSBDB fallback for codes missing from this table —
     * that source usually hands back its own coordinates directly anyway when ours misses. */
    fun lookupByCode(code: String): FlightAirport? {
        val upper = code.trim().uppercase()
        if (upper.isEmpty()) return null
        return BY_ICAO[upper] ?: BY_IATA[upper]
    }

    /**
     * The airport closest to a position, or null if none is within [maxKm]. Used to name the
     * airport a flown leg actually started from/landed at, read off the track rather than
     * trusted schedule data (see [AdsbAircraftSource]).
     */
    fun nearestAirport(lat: Double, lng: Double, maxKm: Double = 25.0): FlightAirport? {
        if (!lat.isFinite() || !lng.isFinite()) return null
        var best: FlightAirport? = null
        var bestKm = maxKm
        // A degree of longitude shrinks toward the poles; without this an airport 25km away at
        // 60°N measures as 12km and the wrong one wins.
        val lngScale = cos(lat * Math.PI / 180)
        for (ap in ALL) {
            val dy = (ap.lat - lat) * 111.32
            val dx = (ap.lng - lng) * 111.32 * lngScale
            val d = hypot(dx, dy)
            if (d < bestKm) {
                bestKm = d
                best = ap
            }
        }
        return best
    }
